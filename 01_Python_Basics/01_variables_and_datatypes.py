# Variables and Data Types Practice

# Integer
age = 21
print("Age:", age, "| Type:", type(age))

# Float
cgpa = 8.5
print("CGPA:", cgpa, "| Type:", type(cgpa))

# String
name = "M"
print("Name:", name, "| Type:", type(name))

# Boolean
is_student = True
print("Is Student:", is_student, "| Type:", type(is_student))

# List
marks = [85, 90, 78]
print("Marks:", marks, "| Type:", type(marks))

# Tuple
coordinates = (10, 20)
print("Coordinates:", coordinates, "| Type:", type(coordinates))

# Set
unique_ids = {1, 2, 3}
print("Unique IDs:", unique_ids, "| Type:", type(unique_ids))

# Dictionary
student = {"name": "M", "course": "BCA", "year": "Final"}
print("Student:", student, "| Type:", type(student))
